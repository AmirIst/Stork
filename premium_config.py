REFERRAL_CONFIG: Dict[str, Any] = {
    "days_per_invite": 1,
    "milestone_invites": 10,
    "milestone_bonus_days": 5,          # 10 + 5 = 15 дней суммарно за 10 рефералов
    "milestone_discount_percent": 50,   # 50% скидка на месячный тариф
}


